"""Generate application manuscript values exclusively from validated results."""
import hashlib
import json
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def render():
    import application_comparison as app
    from fill_tex import fmt, fmt_down, fmt_up
    path = ROOT / "results/application_comparison.json"
    data = json.loads(path.read_text())
    app.validate_results(data, replay=False)
    cfg = data["config"]
    import application_constant_baseline as constant
    constant_path = ROOT / "results/application_constant_baseline.json"
    baseline = json.loads(constant_path.read_text())
    constant.validate_report(baseline)
    if ([row["box_half_width"] for row in baseline["domains"]] != cfg["domain_halfwidths"]
            or baseline["requested_rate"] != cfg["target_rate"]
            or baseline["requested_raw_margin"] != cfg["verification_raw_margin"]):
        raise ValueError("Analytical baseline and neural comparison targets/domains differ")
    macros = {
        "appSeeds": len(cfg["seeds"]), "appTotalRuns": len(data["runs"]),
        "appRate": cfg["target_rate"], "appFloor": cfg["metric_floor"],
        "appTrainMargin": cfg["training_raw_margin"], "appVerifyMargin":cfg["verification_raw_margin"],
        "appSamples":cfg["initial_samples"], "appBatch":cfg["batch_size"],
        "appRounds":cfg["max_rounds"], "appSteps":cfg["training_steps_per_round"],
        "appTotalSteps":cfg["max_rounds"]*cfg["training_steps_per_round"],
        "appLearningRate":cfg["learning_rate"], "appUnits":cfg["hidden_units"],
        "appParameters":cfg["parameters"], "appReturned":cfg["returned_points"],
        "appScreen":cfg["screen_axis_points"], "appBoxBudget":cfg["verification_max_boxes"],
        "appDepthBudget":cfg["verification_max_depth"],
        "appRefinementBudget":cfg["secondary_refinement"]["max_boxes"],
        "appConstKLower":float(Fraction(baseline["domains"][0]["cosine_bounds"]["coarse_interval_rational"][0])),
        "appConstKUpper":float(Fraction(baseline["domains"][0]["cosine_bounds"]["coarse_interval_rational"][1])),
    }
    suffixes = ["Small", "Medium", "Large"]
    small_pair = next(r for r in data["summary"]["paired"]
                      if r["halfwidth"] == cfg["domain_halfwidths"][0]
                      and r["comparator"] == "fitzsimmons_liu_pdi")
    macros["appPdiDiscordantSmall"] = small_pair["cegis_only"] + small_pair["comparator_only"]
    for B, suffix in zip(cfg["domain_halfwidths"], suffixes):
        macros["appB"+suffix] = B
        for method, label in (("cegis_hinge", "Cegis"), ("fitzsimmons_liu_pdi", "Pdi"),
                              ("hinge_fixed", "Fixed")):
            row = next(r for r in data["summary"]["rows"] if r["method"] == method and r["halfwidth"] == B)
            macros["app"+label+suffix] = row["certified"]
            refined = next(r for r in data["summary"]["refinement_rows"] if r["method"] == method and r["halfwidth"] == B)
            macros["appRef"+label+suffix] = refined["certified"]
    lines = ["% Generated by application_report.render through fill_tex.py; do not edit.",
             "% SHA256 results/application_comparison.json: "+hashlib.sha256(path.read_bytes()).hexdigest(),
             "% SHA256 results/application_constant_baseline.json: "+hashlib.sha256(constant_path.read_bytes()).hexdigest(),
             "% Protocol SHA256: "+data["protocol_sha256"]]
    lines += [r"\providecommand{\%s}{%s}" % (key, fmt(value)) for key, value in sorted(macros.items())]
    for B, suffix in zip(cfg["domain_halfwidths"], suffixes):
        lines.append(r"\providecommand{\appEnergy%s}{%s}" %
                     (suffix, fmt_down(data["energy_subsets"][str(B)]["rho_lower"], sig=4)))
    (ROOT/"paper/application_numbers.tex").write_text("\n".join(lines)+"\n")

    tables = [r"\begin{table}[t]", r"\centering\small",
        r"\caption{Matched swing-model comparison. Each row includes every seed. Updates and times are medians over all runs, including failures; early certification stops a run. Equal update and oracle caps do not imply equal wall time.}",
        r"\label{tab:application}", r"\begin{tabular}{clrrrr}", r"\hline",
        r"$B$ & Learner & Cert./seeds & Updates & Learn (s) & Verify (s) \\", r"\hline"]
    for row in data["summary"]["rows"]:
        tables.append(r"$%s$ & %s & %s/%s & $%s$ & $%s$ & $%s$ \\" %
            (fmt(row["halfwidth"]), app.METHOD_LABELS[row["method"]], row["certified"], row["runs"],
             fmt(row["median_updates_all"]), fmt(row["median_learner_s_all"],sig=3),
             fmt(row["median_oracle_s_all"],sig=3)))
    tables += [r"\hline", r"\end{tabular}", r"\end{table}", "",
        r"\begin{table}[t]", r"\centering\small",
        r"\caption{Paired certification outcomes on the swing model. Counts compare the CEGIS hinge learner against the indicated comparator using matched seeds. These descriptive counts do not rank the original published tools.}",
        r"\label{tab:applicationpaired}", r"\begin{tabular}{clrrrr}", r"\hline",
        r"$B$ & Comparator & Both & CEGIS only & Comparator only & Neither \\", r"\hline"]
    for row in data["summary"]["paired"]:
        tables.append(r"$%s$ & %s & %d & %d & %d & %d \\" %
            (fmt(row["halfwidth"]), app.METHOD_LABELS[row["comparator"]], row["both"], row["cegis_only"],
             row["comparator_only"], row["neither"]))
    tables += [r"\hline", r"\end{tabular}", r"\end{table}", "",
        r"\begin{table}[t]", r"\centering\small",
        r"\caption{Exploratory verification-budget refinement of every frozen final candidate. The larger common box budget was selected after preliminary primary outcomes. Additional time and total primary-plus-refinement time are medians over all runs; no learning is repeated and the primary outcomes remain unchanged.}",
        r"\label{tab:applicationrefinement}", r"\begin{tabular}{clrrrr}", r"\hline",
        r"$B$ & Learner & Cert./seeds & Additional cert. & Extra (s) & Total (s) \\", r"\hline"]
    for row in data["summary"]["refinement_rows"]:
        tables.append(r"$%s$ & %s & %d/%d & %d & $%s$ & $%s$ \\" %
            (fmt(row["halfwidth"]), app.METHOD_LABELS[row["method"]], row["certified"], row["runs"],
             row["additional_certified"], fmt(row["median_additional_oracle_s_all"],sig=3),
             fmt(row["median_primary_plus_refinement_s_all"],sig=3)))
    tables += [r"\hline", r"\end{tabular}", r"\end{table}", ""]
    tables += [r"\begin{table}[t]", r"\centering\small",
        r"\caption{Post hoc analytical constant-metric baseline. A single fixed matrix is checked on each whole box at the shared rate and strict margin. There are no training seeds or timing comparisons. A positive diagonal witness rules out this matrix on that box, not other metrics or contraction on its interior energy subset.}",
        r"\label{tab:applicationconstant}", r"\begin{tabular}{clc}", r"\hline",
        r"$B$ & Fixed-$P$ outcome & Proved lower bound on $[C_P(B,0)]_{11}$ \\", r"\hline"]
    for row in baseline["domains"]:
        outcome = "Certified on whole box" if row["certified"] else "Violates requested rate"
        witness = "---" if row["certified"] else "$"+fmt_down(row["violation"]["rayleigh_quotient_lower"],sig=4)+"$"
        tables.append(r"$%s$ & %s & %s \\" % (fmt(row["box_half_width"]),outcome,witness))
    tables += [r"\hline", r"\end{tabular}", r"\end{table}", ""]
    (ROOT/"paper/application_tables.tex").write_text("\n".join(tables))
    print("Generated application numbers and paired comparison tables from",path)


if __name__ == "__main__":
    render()
